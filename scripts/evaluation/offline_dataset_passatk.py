#!/usr/bin/env python3
"""
Minimal script to compute pass@k from pre-generated offline datasets.
Analyzes the saved rewards in datasets produced by generate_offline_math_dataset.py.
"""

import argparse
import os

import datasets
import matplotlib.pyplot as plt
import numpy as np
import polars as pl
from tqdm import tqdm


def pass_at_k(n, c, k):
    """
    Compute the pass@k score.
    :param n: number of samples
    :param c: number of correct answers
    :param k: k value
    :return: pass@k score
    """
    if n - c < k:
        return 1.0
    return 1.0 - np.prod(1.0 - k / np.arange(n - c + 1, n + 1))


def check_response_rewards_consistency(dataset: datasets.Dataset):
    """Check that all responses for a given prompt have consistent response_rewards lengths."""
    df = dataset.to_pandas()
    df["prompt_str"] = df["prompt"].apply(lambda x: str(x[0]["content"]))
    reward_len = None
    for prompt, group in df.groupby("prompt_str"):
        rewards_lists = group["response_rewards"].tolist()
        reward_set = set(tuple(rewards) for rewards in rewards_lists)
        if len(reward_set) > 1:
            raise ValueError(f"Inconsistent number of responses for prompt '{prompt}': {len(reward_set)} different reward lists found.")
        if reward_len is None:
            reward_len = len(rewards_lists[0])
        else:
            if len(rewards_lists[0]) != reward_len:
                raise ValueError(f"Inconsistent number of responses across prompts. Expected {reward_len}, but prompt '{prompt}' has {len(rewards_lists[0])} responses.")


def prepare_dataset(dataset_path: str):
    """Load dataset from path."""
    print(f"Loading dataset from {dataset_path}...")
    dataset = datasets.Dataset.from_polars(pl.read_parquet(dataset_path))  # load with polars to avoid weird issues with large parquet files
    # dataset = datasets.load_dataset("parquet", data_files=dataset_path)["train"]
    check_response_rewards_consistency(dataset)
    # check for column names
    expected_columns = {"prompt", "response", "response_rewards"}
    actual_columns = set(dataset.column_names)
    if not expected_columns.issubset(actual_columns):
        raise ValueError(f"Dataset is missing expected columns. Expected at least: {expected_columns}, but got: {actual_columns}")
    return dataset


def compute_pass_at_k(dataset: datasets.Dataset) -> dict[int, float]:
    """Compute pass@k for k=1 to num_responses from saved rewards.

    If weight_column is provided, resample the dataset according to those weights before computing pass@k.
    """
    pass_at_k_vals = {}
    avg_at_k_vals = {}
    avg_rewards = []
    df = dataset.to_pandas()
    df["prompt_str"] = df["prompt"].apply(lambda x: str(x[0]["content"]))
    num_skipped = 0
    num_total = 0
    for prompt, group in tqdm(df.groupby("prompt_str")):
        num_total += 1
        rewards_lists = group["response_rewards"].tolist()
        reward_set = set(tuple(rewards) for rewards in rewards_lists)
        if len(reward_set) > 1:
            raise ValueError(f"Inconsistent number of responses for prompt '{prompt}': {len(reward_set)} different reward lists found.")
        rewards = group["precomputed_reward"].tolist()

        avg_rewards.append(np.mean(rewards))
        num_responses = len(rewards)
        if len(pass_at_k_vals) == 0:
            pass_at_k_vals = {k: [] for k in range(1, num_responses + 1)}
            avg_at_k_vals = {k: [] for k in range(1, num_responses + 1)}
        else:
            if not len(pass_at_k_vals) == num_responses:
                print(f"Warning: Inconsistent number of responses across prompts. Expected {len(pass_at_k_vals)}, got {num_responses}. Skipping this prompt.")
                num_skipped += 1
                continue
        num_correct = sum(rewards)  # binary rewards
        n = len(rewards)
        for k in range(1, num_responses + 1):
            val = pass_at_k(n, num_correct, k)
            k_sample = rewards[:k]
            avg_val = np.mean(k_sample)
            pass_at_k_vals[k].append(val)
            avg_at_k_vals[k].append(avg_val)
    if num_skipped > 0:
        print(f"Skipped {num_skipped} prompts out of {num_total} due to inconsistent number of responses.")
    return pass_at_k_vals, avg_rewards, avg_at_k_vals


def main():
    parser = argparse.ArgumentParser(description="Compute pass@k from offline datasets with pre-computed rewards")
    parser.add_argument("--dataset_paths", type=str, nargs="+", help="Path(s) to dataset(s) generated by generate_offline_math_dataset.py")
    parser.add_argument("--output_path", type=str, default=None, help="Optional path to save the results")
    args = parser.parse_args()

    if args.output_path:
        print(f"Results will be saved to {args.output_path}")
        if not os.path.exists(args.output_path):
            os.makedirs(args.output_path)
        if not os.path.exists(f"{args.output_path}/plots"):
            os.makedirs(f"{args.output_path}/plots")
    res_df = {"dataset": [], "k": [], "pass_at_k_mean": [], "pass_at_k_std": [], "avg_at_k_mean": [], "avg_at_k_std": []}
    # Process each dataset
    for dataset_path in args.dataset_paths:
        print(f"\n{'=' * 60}")
        print(f"Dataset: {dataset_path}")
        print(f"{'=' * 60}")
        # Load dataset
        dataset = prepare_dataset(dataset_path)
        print(f"\nComputing pass@k for {dataset_path}...")
        pass_at_k, avg_orig_rewards, avg_at_k = compute_pass_at_k(dataset)
        print(f"\n{'k':<10} {'Pass@k':<10}")
        print("-" * 20)
        for k in sorted(pass_at_k.keys()):
            mean_pass_at_k = np.mean(pass_at_k[k])
            std_pass_at_k = np.std(pass_at_k[k])
            mean_avg_at_k = np.mean(avg_at_k[k])
            std_avg_at_k = np.std(avg_at_k[k])
            print(f"{k:<10} {mean_pass_at_k:.4f} ± {std_pass_at_k:.4f}")
            res_df["dataset"].append(dataset_path)
            res_df["k"].append(k)
            res_df["pass_at_k_mean"].append(mean_pass_at_k)
            res_df["pass_at_k_std"].append(std_pass_at_k)
            res_df["avg_at_k_mean"].append(mean_avg_at_k)
            res_df["avg_at_k_std"].append(std_avg_at_k)

        # plot histogram of average rewards per prompt
        plt.figure(figsize=(8, 6))
        plt.hist(avg_orig_rewards, bins=50, density=False)
        plt.title("Histogram of Average Rewards per Prompt")
        plt.xlabel("Average Reward")
        plt.ylabel("Density")
        plt.grid()
        plt.tight_layout()
        if args.output_path:
            plt.savefig(os.path.join(args.output_path, "plots/avg_rewards_per_prompt.png"))
        plt.close()
    res_df = pl.DataFrame(res_df)
    print(args.output_path)
    res_df.write_csv(os.path.join(args.output_path, "pass_at_k_results.csv"))
    print("\nEvaluation complete!")


if __name__ == "__main__":
    main()
